-- Complete the Supabase ERD with tables used by chat, premium and services.

create type public.subscription_status as enum ('active', 'cancelled', 'expired');
create type public.chat_message_kind as enum ('text', 'note');

create table public.chat_messages (
  message_id bigint generated by default as identity primary key,
  sender_id bigint not null references public.users(id) on delete cascade,
  receiver_id bigint not null references public.users(id) on delete cascade,
  message_type public.chat_message_kind not null default 'text',
  message text,
  note_id bigint references public.notes(note_id) on delete set null,
  permission public.share_permission,
  created_at timestamptz not null default now()
);
create index idx_chat_pair on public.chat_messages(sender_id, receiver_id, created_at);
create index idx_chat_note on public.chat_messages(note_id);

create table public.plans (
  id bigint generated by default as identity primary key,
  code varchar(50) not null unique,
  name varchar(100) not null,
  active boolean not null default true
);

create table public.entitlements (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.plans(id) on delete cascade,
  feature_code varchar(64) not null,
  limit_value integer not null,
  unique (plan_id, feature_code)
);

create table public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  plan_id bigint not null references public.plans(id),
  status public.subscription_status not null default 'active',
  starts_at timestamptz not null default now(),
  ends_at timestamptz
);
create index idx_subscription_user on public.subscriptions(user_id, status);

create table public.usage_records (
  user_id bigint not null references public.users(id) on delete cascade,
  feature_code varchar(64) not null,
  period_date date not null,
  used_count integer not null default 0,
  primary key (user_id, feature_code, period_date)
);

create table public.premium_trials (
  user_id bigint primary key references public.users(id) on delete cascade,
  started_at timestamptz not null default now(),
  ends_at timestamptz not null
);

create table public.service_outbox (
  id bigint generated by default as identity primary key,
  aggregate_type varchar(48) not null,
  aggregate_id bigint not null,
  event_type varchar(96) not null,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  published_at timestamptz,
  attempts integer not null default 0 check (attempts >= 0),
  last_error varchar(512)
);
create index idx_outbox_pending on public.service_outbox(published_at, id);
create index idx_outbox_aggregate on public.service_outbox(aggregate_type, aggregate_id, id);

alter table public.chat_messages enable row level security;
alter table public.plans enable row level security;
alter table public.entitlements enable row level security;
alter table public.subscriptions enable row level security;
alter table public.usage_records enable row level security;
alter table public.premium_trials enable row level security;
alter table public.service_outbox enable row level security;

